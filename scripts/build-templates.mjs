#!/usr/bin/env node
/**
 * Assembles the static page templates from shared partials.
 *
 * Templates must be self-contained so anyone can copy one file and go — but the
 * header and footer appearing verbatim in twenty files means a header change is
 * twenty edits that drift apart. So the SOURCE is partials plus per-page bodies,
 * and the OUTPUT is standalone HTML.
 *
 *   design-kit/templates/_partials/*.html   shared chrome
 *   design-kit/templates/_pages/<name>.<desktop|mobile>.html   page body + directives
 *   -> design-kit/templates/<desktop|mobile>/<name>.html
 *
 * Page files start with a JSON directive block:
 *   <!--@ { "title": "...", "bodyClass": "page-bg-search", "header": "desktop" } @-->
 */
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATES = join(ROOT, 'design-kit/templates');
const PARTIALS = join(TEMPLATES, '_partials');
const PAGES = join(TEMPLATES, '_pages');

const partial = (name) => readFileSync(join(PARTIALS, `${name}.html`), 'utf8').trimEnd();

/** Fills {{token}} slots; any slot left unset resolves to an empty string. */
function fill(html, values = {}) {
  return html.replace(/\{\{(\w+)\}\}/g, (_, key) => values[key] ?? '');
}

function buildPage(source, meta) {
  const isMobile = meta.breakpoint === 'mobile';

  let header = '';
  if (meta.header === 'desktop') {
    header = fill(partial('header-desktop'), {
      motorsActive: meta.vertical === 'motors' ? ' header__vertical--active' : '',
      propertyActive: meta.vertical === 'property' ? ' header__vertical--active' : '',
    });
  } else if (meta.header === 'mobile') {
    header = partial('header-mobile');
  } else if (meta.header === 'mobile-back') {
    header = fill(partial('header-mobile-back'), { pageTitle: meta.headerTitle ?? '' });
  }

  const nav = meta.bottomNav
    ? fill(partial('bottom-nav'), {
        homeActive: meta.bottomNav === 'home' ? ' bottom-nav__item--active' : '',
        searchActive: meta.bottomNav === 'search' ? ' bottom-nav__item--active' : '',
        chatActive: meta.bottomNav === 'chat' ? ' bottom-nav__item--active' : '',
        adsActive: meta.bottomNav === 'ads' ? ' bottom-nav__item--active' : '',
      })
    : '';

  const footer = meta.footer === false || isMobile ? '' : partial('footer');

  const bodyClass = [meta.bodyClass, meta.bottomNav ? 'has-bottom-nav' : '']
    .filter(Boolean)
    .join(' ');

  return `<!doctype html>
<!--
  GENERATED by scripts/build-templates.mjs — edit the source, not this file:
    design-kit/templates/_pages/${meta.sourceName}
  Rebuild with: npm run build:templates

  ${meta.note ?? ''}
-->
<html lang="en"${meta.dir ? ` dir="${meta.dir}"` : ''}>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${meta.title}</title>
<link rel="stylesheet" href="../../tokens/tokens.css">
<link rel="stylesheet" href="../../patterns/patterns.css">
</head>
<body${bodyClass ? ` class="${bodyClass}"` : ''}>

${header}

${source.trim()}

${nav}
${footer}
</body>
</html>
`;
}

const DIRECTIVE = /^<!--@([\s\S]*?)@-->/;

const sources = readdirSync(PAGES).filter((f) => f.endsWith('.html')).sort();
if (!sources.length) {
  console.error('No page sources in design-kit/templates/_pages/');
  process.exit(1);
}

const built = [];
for (const file of sources) {
  const raw = readFileSync(join(PAGES, file), 'utf8');
  const match = raw.match(DIRECTIVE);
  if (!match) {
    console.error(`  ${file}: missing <!--@ { ... } @--> directive block`);
    process.exitCode = 1;
    continue;
  }

  let meta;
  try {
    meta = JSON.parse(match[1]);
  } catch (error) {
    console.error(`  ${file}: directive is not valid JSON — ${error.message}`);
    process.exitCode = 1;
    continue;
  }

  // `<name>.<breakpoint>.html` -> desktop/<name>.html
  const parts = file.replace(/\.html$/, '').split('.');
  const breakpoint = parts.pop();
  const name = parts.join('.');
  if (!['desktop', 'mobile'].includes(breakpoint)) {
    console.error(`  ${file}: filename must end .desktop.html or .mobile.html`);
    process.exitCode = 1;
    continue;
  }

  const body = raw.slice(match[0].length);
  const outDir = join(TEMPLATES, breakpoint);
  mkdirSync(outDir, { recursive: true });
  writeFileSync(
    join(outDir, `${name}.html`),
    buildPage(body, { ...meta, breakpoint, sourceName: file }),
  );
  built.push(`${breakpoint}/${name}.html`);
}

/* The gallery is generated from what was actually built, so it can't list a page
   that no longer exists or miss one that was just added. */
const byName = new Map();
for (const path of built) {
  const [breakpoint, file] = path.split('/');
  const name = file.replace(/\.html$/, '');
  if (!byName.has(name)) byName.set(name, {});
  byName.get(name)[breakpoint] = path;
}

const LABELS = {
  home: 'Home',
  motors: 'Motors landing (vertical)',
  properties: 'Properties landing (vertical)',
  search: 'Search results',
  'ad-detail': 'Ad detail',
  'post-ad': 'Post your ad',
  'my-ads': 'My ads',
  chat: 'Chat',
  favourites: 'Favourites',
  'seller-page': 'Seller / agency page',
  login: 'Login or signup',
  payment: 'Payment',
  'not-found': 'Not found / empty state',
};

const ORDER = Object.keys(LABELS);
const sorted = [...byName.keys()].sort(
  (a, b) => (ORDER.indexOf(a) + 1 || 99) - (ORDER.indexOf(b) + 1 || 99),
);

const rows = sorted
  .map((name) => {
    const entry = byName.get(name);
    const links = ['desktop', 'mobile']
      .map((bp) =>
        entry[bp]
          ? `<a class="btn btn--secondary btn--sm" href="${entry[bp]}">${bp}</a>`
          : `<span class="pill pill--regular">no ${bp}</span>`,
      )
      .join(' ');
    return `      <tr><td>${LABELS[name] ?? name}</td><td>${links}</td></tr>`;
  })
  .join('\n');

writeFileSync(
  join(TEMPLATES, 'index.html'),
  `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>dubizzle Egypt — Page Templates</title>
<link rel="stylesheet" href="../tokens/tokens.css">
<link rel="stylesheet" href="../patterns/patterns.css">
</head>
<body>
<main class="container section">
  <h1 class="section__title">Page Templates</h1>
  <p class="empty-state__body" style="margin:0.8rem 0 2.4rem;max-width:64rem;text-align:start">
    ${built.length} generated templates. Copy one and swap the content — don't start from a blank page.
    Sources live in <code>_pages/</code>, shared chrome in <code>_partials/</code>; rebuild with
    <code>npm run build:templates</code>.
  </p>
  <div class="pane">
    <table class="table">
      <thead><tr><th>Page</th><th>Breakpoint</th></tr></thead>
      <tbody>
${rows}
      </tbody>
    </table>
  </div>
</main>
</body>
</html>
`,
);

console.log(`Built ${built.length} template(s) + index.html:`);
for (const name of built) console.log(`  ${name}`);
