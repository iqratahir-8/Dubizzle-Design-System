#!/usr/bin/env node
/**
 * Links the consumer templates into a clickable prototype — desktop and mobile.
 *
 * Every template under design-kit/templates/{desktop,mobile}/ (except the agency
 * portal, which scripts/build-live-templates.mjs wires itself) gets its live links
 * rewritten to the sibling template they land on, its button-driven states wired as
 * hotspots, and the prototype runtime appended. The rules live in
 * scripts/lib/consumer-prototype.mjs.
 *
 * Runs on the BUILT templates, not the captures, so it works in a clone that has no
 * design-kit/reference/live/ (the account captures never leave the capturing machine).
 * It is idempotent: a wired template is unwired first, then wired again.
 *
 * Writes design-kit/templates/_prototype.json — what links where, per layout — which
 * scripts/build-flows.mjs turns into the per-section flows.
 *
 *   npm run wire:prototype          (also runs as part of npm run build:templates)
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { prototypeRuntime } from './lib/prototype.mjs';
import { wireConsumer, unwire, consumerHotspotsFor, sectionOf } from './lib/consumer-prototype.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const TEMPLATES = join(ROOT, 'design-kit/templates');
const LAYOUTS = ['desktop', 'mobile'];

const manifest = { _purpose: 'Generated by scripts/wire-prototype.mjs: which template each wired link and hotspot leads to, per layout. Input to scripts/build-flows.mjs.', generated: new Date().toISOString().slice(0, 10), layouts: {} };
let totalWired = 0;
let totalNeutralised = 0;
let totalHotspots = 0;

for (const layout of LAYOUTS) {
  const dir = join(TEMPLATES, layout);
  const pages = readdirSync(dir).filter((f) => f.endsWith('.html') && !f.startsWith('portal-')).map((f) => f.replace(/\.html$/, '')).sort();
  const isAvailable = (target) => existsSync(join(dir, `${target}.html`));
  manifest.layouts[layout] = {};
  for (const page of pages) {
    const file = join(dir, `${page}.html`);
    const html = unwire(readFileSync(file, 'utf8'));
    const r = wireConsumer(html, { layout, page }, isAvailable);
    const hotspots = consumerHotspotsFor(layout, page, isAvailable);
    const runtime = `<!-- proto-runtime:consumer -->\n${prototypeRuntime({ id: `consumer-${layout}` }, hotspots)}\n<!-- /proto-runtime:consumer -->`;
    const out = /<\/body>/i.test(r.html) ? r.html.replace(/<\/body>/i, `${runtime}\n</body>`) : `${r.html}\n${runtime}`;
    writeFileSync(file, out);
    const links = {};
    for (const [target, e] of r.links) links[target] = { count: e.count, texts: [...(e.texts || [])], representative: e.representative };
    manifest.layouts[layout][page] = { section: sectionOf(page), links, hotspots, neutralised: r.neutralised };
    totalWired += r.wired;
    totalNeutralised += r.neutralised;
    totalHotspots += hotspots.length;
    console.log(`proto ${layout}/${page}.html`.padEnd(48) + `${String(r.wired).padStart(4)} links → ${Object.keys(links).length} screens, ${r.neutralised} neutralised, ${hotspots.length} hotspot(s)`);
  }
}

writeFileSync(join(TEMPLATES, '_prototype.json'), JSON.stringify(manifest, null, 1) + '\n');
console.log(`\n${totalWired} links wired, ${totalNeutralised} neutralised, ${totalHotspots} hotspots · design-kit/templates/_prototype.json`);
